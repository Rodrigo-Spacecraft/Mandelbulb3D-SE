"""Generate prepared-context C kernels for the bundled native formula catalog.

Only functions with a statically scalarized body and understood helpers qualify.
Unknown memory access retains the full native C function. Preserve record,
parameter, scratch and register side effects; map live XYZ/Julia/4D/DE inputs
straight from the caller instead of first serializing them to scratch memory.
LGPL-2.1-or-later, following the bundled native translations.
"""
from pathlib import Path
import re,json
ROOT=Path(__file__).resolve().parent.parent
NATIVE=ROOT/'native-c'
ALLOWED={'cn_alu','cn_bits','cn_cell','cn_compare','cn_cond','cn_double','cn_float','cn_reg_get','cn_reg_set','cn_shift_reg_l','cn_swap','cn_round','cn_fast_sin','cn_fast_cos','cn_remainder','cn_map_px'}
FIELDS={3:'xyz[0]',4:'xyz[1]',5:'xyz[2]',6:'fourth',10:'constant[0]',11:'constant[1]',12:'constant[2]',14:'radius',32:'scale',36:'derivative'}
record_read=re.compile(r'cn_rd64\(m,CN_REC\+8\*\((\d+)\)\)')
record_write=re.compile(r'cn_wr64\(m,CN_REC\+8\*\((\d+)\),(r\d+)\);')
def write_changed(path,text):
    text=text.rstrip()+chr(10)
    if not path.exists() or path.read_text()!=text:path.write_text(text)
plans={};skipped={}
prefer_native=set(json.loads((NATIVE/'compact-tuning.json').read_text())['prefer_native'])
for source in sorted(NATIVE.glob('part*.c')):
    out=['/* Generated by tools/generate-catalog-compact.py; LGPL-2.1-or-later. */','#include "compact.h"']
    for original in re.split(r'(?=\nint cn_f_)',source.read_text()):
        match=re.match(r'\s*int (cn_f_\w+)\(',original)
        if not match:continue
        name=match[1];start=original.find('\n{\n');end=original.find('cn_break_body:;')
        if start<0 or end<0:
            skipped[name]='requires dynamic native state';continue
        body=original[start:end]
        extra=set(re.findall(r'\bcn_\w+(?=\()',body))-ALLOWED
        unknown_state=set(re.findall(r'm->(\w+)',body)) - {'xmm','cw'}
        if unknown_state:
            skipped[name]='unrecognized native state: '+', '.join(sorted(unknown_state));continue
        if extra:
            skipped[name]='body memory helper: '+', '.join(sorted(extra));continue
        pre=original[:start];epi=original[end:]
        vm=re.search(r'__auto_type \w+ = cn_ptr\(m,\(\(uint32_t\)\(vb\+(\d+)\)\)\); unsigned char \* vm = \w+;',pre)
        if vm:
            offset=int(vm[1]);pre=pre[:vm.start()]+pre[vm.end():]
        elif re.search(r'\bvm\b',body+epi):
            skipped[name]='unrecognized parameter layout';continue
        else:offset=0
        # Normalize statically addressed record cells, including dIFS variants.
        pre=re.sub(r'cn_rd64u?\(m,0x([0-9a-fA-F]+)U\)',lambda m:'cn_rd64(m,CN_REC+8*('+str((int(m[1],16)-0x10001000)//8)+'))' if 0x10001000<=int(m[1],16)<0x10001200 and int(m[1],16)%8==0 else m[0],pre)
        epi=re.sub(r'cn_wr64u?\(m,0x([0-9a-fA-F]+)U,(r\d+)\);',lambda m:'cn_wr64(m,CN_REC+8*('+str((int(m[1],16)-0x10001000)//8)+'),'+m[2]+');' if 0x10001000<=int(m[1],16)<0x10001200 and int(m[1],16)%8==0 else m[0],epi)
        reads={int(n) for n in record_read.findall(pre)}
        writes={int(n) for n,_ in record_write.findall(epi)}
        pre=re.sub(r'^\s*int cn_f_\w+\([^\n]+\n', '',pre,count=1)
        pre=pre.replace('CN_U8 cn_initial_regs=*regs;', 'CN_U8 cn_initial_regs=ctx->regs;')
        # The declaration above normally shares the removed signature line.
        pre='CN_U8 cn_initial_regs=ctx->regs;uint64_t max_steps=2000000;\n'+pre
        pre=pre.replace('(*regs)','(ctx->regs)').replace('*regs','ctx->regs').replace('m->regs','ctx->regs')
        pre=record_read.sub(lambda m:'cn_dbits(ctx->'+FIELDS[int(m[1])]+')' if int(m[1]) in FIELDS else m[0],pre)
        epi=record_write.sub(lambda m:(m[0] if int(m[1]) in {14,32,36} else '')+'ctx->'+FIELDS[int(m[1])]+'=cn_double('+m[2]+');' if int(m[1]) in FIELDS else m[0],epi)
        epi=epi.replace('(*regs)','(ctx->regs)').replace('*regs','ctx->regs')
        # The full executor zeros SSE registers before every formula call.
        # Keep them local: no following call may observe these temporary values.
        xmm=set(re.findall(r'm->xmm\[([^\]]+)\]',pre+body+epi))
        if any(not index.isdigit() or not 0<=int(index)<8 for index in xmm):
            skipped[name]='dynamic vector-register index';continue
        if xmm:
            pre='CN_U2 xmm[8]={{0}};\n'+pre
            pre=pre.replace('m->xmm','xmm');body=body.replace('m->xmm','xmm');epi=epi.replace('m->xmm','xmm')
        kernel=name.replace('cn_f_','cn_compact_')
        out.append('int '+kernel+'(CN_CompactContext *ctx,const unsigned char *vm,uint32_t pvar){\nCN_Machine *m=ctx->machine;\n'+pre+body+epi)
        plans[name]=(kernel,offset,sum(1<<n for n in reads),sum(1<<n for n in writes),sum(bit for key,bit in [("xmm",1),("fl",2),("fsw_cc",4),("steps",8)] if "m->"+key in pre+body+epi))
    write_changed(NATIVE/('compact-'+source.name),'\n'.join(out)+'\n')
lookup=['/* Generated; LGPL-2.1-or-later. */','#include "compact.h"','#include <strings.h>']
for kernel,_,_,_,_ in plans.values():lookup.append('extern int '+kernel+'(CN_CompactContext *,const unsigned char *,uint32_t);')
lookup.append('CN_CompactPlan cn_compact_lookup(const char *name){')
for alias,function in re.findall(r'if\(!strcasecmp\(name,"([^"]+)"\)\)return (cn_f_\w+);',(NATIVE/'lookup.c').read_text()):
    if function in plans:
        kernel,offset,mask,writes,state=plans[function];state|=16 if alias in prefer_native else 0;lookup.append('if(!strcasecmp(name,'+json.dumps(alias)+'))return (CN_CompactPlan){'+kernel+','+str(offset)+',UINT64_C('+str(mask)+'),UINT64_C('+str(writes)+'),'+str(state)+'};')
lookup.append('return (CN_CompactPlan){0};}')
write_changed(NATIVE/'compact-lookup.c','\n'.join(lookup)+'\n')
write_changed(NATIVE/'compact-report.json',json.dumps({'prepared_kernels':len(plans),'native_fallbacks':skipped,'prefer_native':sorted(prefer_native)},indent=2)+'\n')
print('Prepared context kernels:',len(plans),'native fallbacks:',len(skipped))
