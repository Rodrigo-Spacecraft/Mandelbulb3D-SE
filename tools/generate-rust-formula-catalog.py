"""Build the checked-in C catalog from formula_catalog's engine metadata.
Run from the repository root after running the Rust example to a TSV file.
"""
from pathlib import Path
import json,re,sys
root=Path(__file__).resolve().parent.parent
old=dict((name.lower(),int(kind)) for kind,name in re.findall(r'case (\d+):return "([^"]+)";', (root/'formula_support.h').read_text().split('static const FormulaParameter')[0]))
entries=[]
for line in Path(sys.argv[1]).read_text().splitlines():
    row=line.split('\t')
    if row[0]=='F':
        _,builtin,name,de,rstop=row
        entry=dict(name=name,builtin=int(builtin),de=int(de),rstop=float(rstop),parameters=[]);entries.append(entry)
    elif row[0]=='P':
        _,ty,default,name=row;entry['parameters'].append((name,int(ty),float(default)))
extras=[e for e in entries if e['name'].lower() not in old]
ids=set(old.values())
def identity(name):
    h=2166136261
    for b in name.lower().encode():h=((h^b)*16777619)&0xffffffff
    n=1000+h%1000000000
    assert n not in ids, f"ID collision: {name}"
    ids.add(n);return n
def quote(s):return json.dumps(s,ensure_ascii=False)
def category(de):return {2:1,11:1,4:2,5:3,6:3,-1:4,-2:4,20:5,21:6,22:6}.get(de,0)
out=['/* Generated by tools/generate-rust-formula-catalog.py from the local Rust engine. */','static const RustFormula rust_formulas[]={']
for e in extras:
    n=identity(e['name']);p=e['parameters'];spec=[]
    for name,ty,v in p:
        lo,hi,integer=(-2147483648,2147483647,1) if ty==2 else (-1e100,1e100,0)
        spec.append('{%s,%.17g,%.17g,%.17g,%d}'%(quote(name),lo,hi,v,integer))
    out.append('{%d,%s,%d,%d,%d,%.17g,%d,{%s},{%s}},'%(n,quote(e['name']),e['builtin'],category(e['de']),e['de'],e['rstop'],len(p),','.join(spec) or '{0}',','.join(str(t) for _,t,_ in p) or '0'))
out+=['};','#define RUST_FORMULA_COUNT (sizeof rust_formulas/sizeof *rust_formulas)','']
(root/'rust_formula_catalog.h').write_text('\n'.join(out))
print(f'{len(entries)} engine formulas; {len(extras)} additions to the existing {len(old)} formulas.')
